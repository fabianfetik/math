#!/usr/bin/env python3
"""Separate exact verification of marked-core's real cover and auxiliary obstruction.

No returned Python is imported. Word domains are recovered from occurrence
spans, splitting strides are generated recursively from all small rooted
trees, contradiction combinations are checked after integer scaling, and
the negative graph is regenerated by BFS and sorted by Kahn's algorithm.
The written reconstruction and the existing five-task theorem remain premises.
Usage: python3 verify_marked_core.py PATH_TO_CERTIFICATE.zip
"""
from collections import Counter, deque
from fractions import Fraction as F
from functools import lru_cache
import hashlib
import itertools
import json
from math import lcm, prod
from pathlib import Path
import sys
import zipfile

if not __debug__:
    raise RuntimeError('Exact checks require assertions enabled.')
path=Path(sys.argv[1])
archive=zipfile.ZipFile(path)
def read(name):
    return json.loads(archive.read(name))

N=5
TARGET=F(3403,4290)
def row(coeff,rhs,strict=False):
    return tuple(map(F,coeff)),F(rhs),bool(strict)
def coordinate(i):
    return [int(j==i) for j in range(N)]

def compositions(n,k):
    if k==1:
        yield (n,)
    else:
        for first in range(1,n-k+2):
            for rest in compositions(n-first,k-1):
                yield (first,)+rest

@lru_cache(None)
def tree_patterns(leaves):
    if leaves==1:
        return frozenset({(1,)})
    result=set()
    for degree in range(2,leaves+1):
        for counts in compositions(leaves,degree):
            for children in itertools.product(*(tree_patterns(n) for n in counts)):
                result.add(tuple(sorted(degree*x for child in children for x in child)))
    return frozenset(result)

def rank_profile(word):
    n=len(word)
    assert n and set(word)==set(range(N))
    result=[]
    for label in range(N):
        times=[i for i,c in enumerate(word) if c==label]
        count=len(times)
        extended=times+[t+n for t in times]
        cap=F(count,n)
        closed=True
        # ceil(k/r)>=G is equivalent to r<k/(G-1) when G>=2.
        for k in range(1,count):
            gap=max(extended[j+k]-times[j] for j in range(count))
            if gap<=1:
                continue
            bound=F(k,gap-1)
            if bound<=cap:
                cap=bound
                closed=False
        result.append((cap,closed))
    return result

raw_terms=read('certificate/terminals.json')
terms=[]
kinds=Counter()
periods=[]
for entry in raw_terms:
    m=entry['metadata'];kind=m['type'];expected=[]
    kinds[kind]+=1
    if kind=='word':
        profile=rank_profile(m['word'])
        assert [[str(c),closed] for c,closed in profile]==m['profile']
        expected=[row(coordinate(i),cap,not closed) for i,(cap,closed) in enumerate(profile)]
        periods.append(len(m['word']))
    elif kind=='forest':
        g,h=m['G'],m['H'];d,e=m['d'],m['e']
        assert g and h and sorted(g+h)==list(range(N))
        assert len(g)==len(d) and len(h)==len(e)
        assert tuple(sorted(d)) in tree_patterns(len(g))
        assert tuple(sorted(e)) in tree_patterns(len(h))
        for i,x in zip(g,d):
            for j,y in zip(h,e):
                coeff=[0]*N;coeff[i]=x;coeff[j]=y
                expected.append(row(coeff,1))
    elif kind=='block2':
        i=m['head'];assert type(i) is int and 0<=i<N
        expected=[row(coordinate(i),F(1,2),True),row([int(j!=i) for j in range(N)],F(5,12))]
    else:
        raise AssertionError(('Unproved terminal type',kind))
    decoded=[row(*r) for r in entry['constraints']]
    assert sorted(decoded)==sorted(expected)
    terms.append(expected)

roots=[];leaf_types=Counter();used=set();binding=0;best=None
for mark in range(N):
    data=read(f'certificate/root{mark}.json')
    assert data['j']==mark and F(data['target'])==TARGET
    base=[]
    for j in range(N-1):
        coeff=[0]*N;coeff[j]=-1;coeff[j+1]=1
        base.append(row(coeff,0))
    coeff=[0]*N;coeff[mark]+=1;coeff[-1]-=2
    base.append(row(coeff,0))
    base.append(row([-1]*N,F(-5,6),True))
    coeff=[F(1)]*N;coeff[mark]=F(1,2)
    base.append(row(coeff,TARGET,True))
    nodes=data['nodes'];pending=[(0,base,0)];seen=set();branches=leaves=depthmax=0
    while pending:
        idx,conditions,depth=pending.pop()
        assert type(idx) is int and 0<=idx<len(nodes) and idx not in seen
        seen.add(idx);depthmax=max(depthmax,depth);node=nodes[idx]
        if node['type']=='branch':
            tid=node['terminal'];assert type(tid) is int and 0<=tid<len(terms)
            used.add(tid);branches+=1
            # Preserve the archive's conjunct order when assigning children.
            original_rows=[row(*r) for r in raw_terms[tid]['constraints']]
            assert len(node['children'])==len(original_rows)
            for child,(coeff,rhs,strict) in zip(node['children'],original_rows):
                failed=row([-v for v in coeff],-rhs,not strict)
                pending.append((child,conditions+[failed],depth+1))
        else:
            assert node['type']=='leaf'
            weights={}
            for k,v in node['multipliers']:
                assert type(k) is int and 0<=k<len(conditions) and k not in weights
                weights[k]=F(v);assert weights[k]>0
            assert weights
            products=[[v*a for a in conditions[k][0]]+[v*conditions[k][1]] for k,v in weights.items()]
            scale=lcm(*(x.denominator for vector in products for x in vector))
            sums=[sum(int(scale*vector[j]) for vector in products) for j in range(N+1)]
            assert all(a>=0 for a in sums[:N])
            strict=any(conditions[k][2] for k in weights)
            assert sums[-1]<0 or (sums[-1]==0 and strict)
            leaf_types['negative' if sums[-1]<0 else 'strict_zero']+=1
            if sums[-1]==0:
                assert weights.get(6,F(0))>0
                binding+=1
            if 6 in weights:
                limit=-sum(v*conditions[k][1] for k,v in weights.items() if k!=6)/weights[6]
                best=limit if best is None else min(best,limit)
            leaves+=1
    assert len(seen)==len(nodes)
    roots.append(dict(mark=mark+1,nodes=len(nodes),branches=branches,leaves=leaves,max_depth=depthmax))
assert len(used)==len(terms)==145 and best==TARGET

negative=read('auxiliary/obstruction.json')
rates=tuple(map(F,negative['rates']))
assert rates==tuple(map(F,['3/11','1/5','1/6','2/13','3/22']))
p=tuple(r.numerator for r in rates);q=tuple(r.denominator for r in rates)
zero=(0,)*N
adj={};queue=deque([zero]);discovered={zero}
while queue:
    state=queue.popleft();children=[]
    for label in range(N):
        target=tuple(max(0,state[i]+p[i]-(q[i] if i==label else 0)) for i in range(N))
        if all(target[i]<q[i] for i in range(N)):
            children.append(target)
            if target not in discovered:
                discovered.add(target);queue.append(target)
    adj[state]=children
assert discovered==set(map(tuple,negative['states_in_postorder']))
indegree=dict.fromkeys(discovered,0)
for children in adj.values():
    for state in children:indegree[state]+=1
queue=deque(state for state,count in indegree.items() if count==0)
distance={zero:0};ordered=[]
while queue:
    state=queue.popleft();ordered.append(state)
    for child in adj[state]:
        distance[child]=max(distance.get(child,0),distance[state]+1)
        indegree[child]-=1
        if indegree[child]==0:queue.append(child)
assert len(ordered)==len(discovered)==4413
assert max(distance.values())==101
assert sum(map(len,adj.values()))==6912
assert sum(rates)-rates[0]/2==TARGET

preimage=read('auxiliary/original-preimage.json')
original=list(map(F,preimage['rates']))
assert sum(original)==TARGET+F(1,100000)<F(5,6)
def merge(pair):
    i,j=pair
    return sorted([x for k,x in enumerate(original) if k not in pair]+[2*max(original[i],original[j])],reverse=True)
assert sorted(original[i] for i in preimage['smallest_pair'])==sorted(original)[:2]
assert merge(preimage['smallest_pair'])==list(rates)
i,j=preimage['equal_pair'];assert original[i]==original[j]
assert sum(merge(preimage['equal_pair']))==sum(original)
boundary=read('auxiliary/boundary-word.json')
boundary_profile=rank_profile([int(x)-1 for x in boundary['word']])
assert [[str(c),flag] for c,flag in boundary_profile]==boundary['profile']
assert boundary_profile[3]==(F(2,13),False)
for i,x in enumerate(boundary['fixed_rates']):
    if x is not None:
        cap,closed=boundary_profile[i]
        assert F(x)<=cap if closed else F(x)<cap

print(json.dumps(dict(status='pass',archive_sha256=hashlib.sha256(path.read_bytes()).hexdigest(),target=str(TARGET),improvement=str(TARGET-F(79,100)),remaining_gap=str(F(5,6)-TARGET),terminal_kinds=dict(kinds),word_period_range=[min(periods),max(periods)],roots=roots,leaf_types=dict(leaf_types),strict_endpoint_leaves=binding,maximum_stored_multiplier_threshold=str(best),negative_graph=dict(states=len(adj),edges=sum(map(len,adj.values())),full_box=prod(q),longest_safe_prefix=max(distance.values()),acyclic=True),preimage_density=str(sum(original)),boundary_period=len(boundary['word']),scope='Separate exact finite verification. Unbounded reconstruction and the existing five-task theorem remain written/formalized premises at their recorded scope.'),indent=2))
