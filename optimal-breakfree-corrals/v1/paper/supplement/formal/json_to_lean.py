#!/usr/bin/env python3
"""Translate the height-seven JSON values to Lean literals; do no math checking.

Only the JSON schema/types are checked here. Header values, array lengths,
ordering, permutations, reference rows, and arrivals are all checked by Lean.
The generated source is deterministic and contains the input byte SHA-256.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Any


FIELDS = {"height", "order", "width", "rows", "permutations", "shifts"}


def fail(message: str) -> None:
    raise ValueError(message)


def no_duplicates(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            fail(f"duplicate JSON object key: {key!r}")
        result[key] = value
    return result


def reject_noninteger(token: str) -> None:
    fail(f"noninteger JSON number or nonstandard numeric constant: {token!r}")


def integer(value: Any, label: str, *, natural: bool) -> int:
    # bool is an int subclass in Python, hence the exact-type test.
    if type(value) is not int:
        fail(f"{label} must be a JSON integer, not {type(value).__name__}")
    if natural and value < 0:
        fail(f"{label} must be nonnegative for its Lean Nat type")
    return value


def load_certificate(path: Path) -> tuple[bytes, dict[str, Any]]:
    raw = path.read_bytes()
    data = json.loads(
        raw.decode("utf-8"),
        object_pairs_hook=no_duplicates,
        parse_float=reject_noninteger,
        parse_constant=reject_noninteger,
    )
    if type(data) is not dict or set(data) != FIELDS:
        fail("top-level object must have exactly height/order/width/rows/permutations/shifts")
    for name in ("height", "order", "width"):
        integer(data[name], name, natural=True)
    for name in ("rows", "permutations"):
        if type(data[name]) is not list:
            fail(f"{name} must be an array")
        for s, values in enumerate(data[name]):
            if type(values) is not list:
                fail(f"{name}[{s}] must be an array")
            for j, value in enumerate(values):
                integer(value, f"{name}[{s}][{j}]", natural=True)
    if type(data["shifts"]) is not list:
        fail("shifts must be an array")
    for s, value in enumerate(data["shifts"]):
        integer(value, f"shifts[{s}]", natural=False)
    return raw, data


def natural_list(values: list[int]) -> str:
    return "[" + ", ".join(str(value) for value in values) + "]"


def nested_list(rows: list[list[int]]) -> str:
    if not rows:
        return "[]"
    return "[\n    " + ",\n    ".join(natural_list(row) for row in rows) + "\n  ]"


def render(raw: bytes, data: dict[str, Any], mode: str = "check") -> str:
    digest = hashlib.sha256(raw).hexdigest()
    shifts = "[" + ", ".join(f"({value} : Int)" for value in data["shifts"]) + "]"
    lines = [
        "import HeightSevenCertificate",
        "",
        "-- Generated by json_to_lean.py; input bytes SHA-256:",
        f"-- {digest}",
        "-- Array order and every integer value are preserved verbatim as values.",
        "set_option maxRecDepth 100000",
        "set_option maxHeartbeats 0",
        "",
        "namespace HeightSevenCertificate",
        "",
        f'def inputSHA256 : String := "{digest}"',
        "",
        "def supplied : Certificate := {",
        f"  height := {data['height']}",
        f"  order := {data['order']}",
        f"  width := {data['width']}",
        f"  rows := {nested_list(data['rows'])}",
        f"  permutations := {nested_list(data['permutations'])}",
        f"  shifts := {shifts}",
        "}",
        "",
        "theorem supplied_header : HeaderOK supplied := by decide",
        "theorem supplied_shape : ShapeOK supplied := by decide",
        "",
        "theorem supplied_row_sites : ∀ s : Fin 7,",
        "    (storedRow supplied s).toFinset = CorralFormalization.OneSwapOdd.R 2 s := by",
        "  intro s",
        "  fin_cases s <;> decide",
        "",
        "theorem supplied_rows : RowsOK supplied :=",
        "  rowsOK_of_checks (by decide) supplied_row_sites",
        "",
        "theorem supplied_permutations : PermutationsOK supplied := by decide",
    ]
    if mode == "check":
        lines.extend([
            "theorem supplied_arrivals : ArrivalsOK supplied := by decide",
            "",
            "theorem supplied_checked : Valid supplied :=",
            "  ⟨supplied_header, supplied_shape, supplied_rows,",
            "    supplied_permutations, supplied_arrivals⟩",
            "",
            "#print axioms supplied_checked",
        ])
    elif mode == "diagnose-shift-mutation":
        lines.extend([
            "",
            "-- A separate kernel proof that the mathematical comparison is false.",
            "theorem supplied_row0_arrivals_rejected :",
            "    ¬ (arrivals supplied (0 : Fin 7)).Perm (storedRow supplied (0 : Fin 7)) := by decide",
            "",
            "theorem supplied_other_arrivals :",
            "    ∀ s : Fin 7, s.val ≠ 0 → (arrivals supplied s).Perm (storedRow supplied s) := by decide",
            "",
            "theorem supplied_arrivals_rejected : ¬ ArrivalsOK supplied := by",
            "  intro h",
            "  exact supplied_row0_arrivals_rejected (h 0)",
            "",
            "theorem supplied_rejected : ¬ Valid supplied := by",
            "  intro h",
            "  exact supplied_arrivals_rejected h.2.2.2.2",
            "",
            "#print axioms supplied_header",
            "#print axioms supplied_shape",
            "#print axioms supplied_rows",
            "#print axioms supplied_permutations",
            "#print axioms supplied_row0_arrivals_rejected",
            "#print axioms supplied_other_arrivals",
            "#print axioms supplied_arrivals_rejected",
            "#print axioms supplied_rejected",
        ])
    else:
        fail(f"unknown mode {mode!r}")
    return "\n".join(lines + ["", "end HeightSevenCertificate", ""])


def generate(input_path: Path, output_path: Path, *, mode: str = "check") -> dict[str, Any]:
    raw, data = load_certificate(input_path)
    source = render(raw, data, mode)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(source, encoding="utf-8")
    return {
        "input_file": input_path.name,
        "input_sha256": hashlib.sha256(raw).hexdigest(),
        "input_bytes": len(raw),
        "output_file": output_path.name,
        "output_sha256": hashlib.sha256(source.encode("utf-8")).hexdigest(),
        "mode": mode,
        "mapping": "All six fields; same nested-array positions and integer values",
        "mathematical_prechecks": False,
        "shape_prechecks": False,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--mode", choices=("check", "diagnose-shift-mutation"), default="check")
    parser.add_argument("--metadata", type=Path)
    args = parser.parse_args()
    try:
        metadata = generate(args.input, args.output, mode=args.mode)
    except (ValueError, UnicodeError, OSError) as error:
        parser.exit(2, f"JSON-to-Lean import error: {error}\n")
    text = json.dumps(metadata, indent=2) + "\n"
    if args.metadata:
        args.metadata.parent.mkdir(parents=True, exist_ok=True)
        args.metadata.write_text(text, encoding="utf-8")
    print(text, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
